<?php

namespace Tests\Unit;

use App\Services\KigakuCalendar;
use Carbon\CarbonImmutable;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\TestCase;

class KigakuCalendarTest extends TestCase
{
    #[DataProvider('dayBoundaries')]
    public function test_daily_stars_at_normal_and_leap_transitions(string $date, int $star, string $cycle): void
    {
        $board = app(KigakuCalendar::class)->board($date, 'day');
        $this->assertSame($star, $board['center_star']);
        $this->assertSame($cycle, $board['cycle']);
    }

    public static function dayBoundaries(): array
    {
        // Published calendar values, not values generated by KigakuCalendar:
        // https://yakumoin.info/about/kyusei_calendar (2026)
        // https://www.magicwands.jp/calculator/calendar/?month=6&year=2020 (summer leap)
        // https://www.magicwands.jp/calculator/calendar/?month=12&year=2031 (winter leap)
        return [
            ['2026-06-18', 9, '陽遁'], ['2026-06-19', 9, '陰遁'], ['2026-06-20', 8, '陰遁'],
            ['2026-12-15', 1, '陰遁'], ['2026-12-16', 1, '陽遁'], ['2026-12-17', 2, '陽遁'],
            ['2020-06-19', 3, '陽遁'], ['2020-06-20', 3, '陰遁'], ['2020-06-21', 2, '陰遁'],
            ['2031-12-19', 7, '陰遁'], ['2031-12-20', 7, '陽遁'], ['2031-12-21', 8, '陽遁'],
        ];
    }

    #[DataProvider('publishedSolarTerms')]
    public function test_solar_terms_match_independent_naoj_times_in_ict(int $year, string $term, string $expected): void
    {
        $actual = app(KigakuCalendar::class)->term($year, $term);
        // NAOJ publishes minutes; allow rounding and the library's small ephemeris differences.
        $this->assertLessThan(61, abs($actual->getTimestamp() - CarbonImmutable::parse($expected, '+07:00')->getTimestamp()));
        $this->assertSame(substr($expected, 0, 10), $actual->toDateString());
    }

    public static function publishedSolarTerms(): array
    {
        // NAOJ's published JST timestamps minus two hours, independently fixed as ICT.
        // https://eco.mtk.nao.ac.jp/koyomi/yoko/2017/rekiyou172.html
        // https://eco.mtk.nao.ac.jp/koyomi/yoko/2026/rekiyou262.html
        return [
            [2017, '立春', '2017-02-03 22:34:00'],
            [2026, '立春', '2026-02-04 03:02:00'],
            [2026, '惊蛰', '2026-03-05 20:59:00'],
            [2026, '芒种', '2026-06-05 22:48:00'],
            [2026, '夏至', '2026-06-21 15:25:00'],
            [2026, '冬至', '2026-12-22 03:50:00'],
        ];
    }

    public function test_year_month_and_day_boundaries_use_local_dates(): void
    {
        $calendar = app(KigakuCalendar::class);
        // 2017 Li Chun is Feb 3 in Vietnam and Feb 4 in Japan; do not reuse the Japanese date.
        $this->assertSame('2017-02-03', $calendar->term(2017, '立春')->toDateString());
        $this->assertSame(['center_star' => 2, 'branch' => 8], $calendar->board('2017-02-02', 'year'));
        $this->assertSame(['center_star' => 1, 'branch' => 9], $calendar->board('2017-02-03', 'year'));
        $this->assertSame(['center_star' => 9, 'branch' => 1], $calendar->board('2017-02-02', 'month'));
        $this->assertSame(['center_star' => 8, 'branch' => 2], $calendar->board('2017-02-03', 'month'));
        $this->assertSame(['center_star' => 8, 'branch' => 2], $calendar->board('2026-03-04', 'month'));
        $this->assertSame(['center_star' => 7, 'branch' => 3], $calendar->board('2026-03-05', 'month'));
        $this->assertSame(['center_star' => 5, 'branch' => 5], $calendar->board('2026-06-04', 'month'));
        $this->assertSame(['center_star' => 4, 'branch' => 6], $calendar->board('2026-06-05', 'month'));
        $this->assertSame(['center_star' => 9, 'branch' => 1], $calendar->board('2026-01-06', 'month'));
        $this->assertSame(11, $calendar->board('2026-06-18', 'day')['branch']);
        $this->assertSame(0, $calendar->board('2026-06-19', 'day')['branch']);
        config(['lucky.timezone' => 'Asia/Tokyo']);
        $this->assertSame('2017-02-04', $calendar->term(2017, '立春')->toDateString());
        $this->assertSame(['center_star' => 2, 'branch' => 8], $calendar->board('2017-02-03', 'year'));
        $this->assertSame(['center_star' => 5, 'branch' => 5], $calendar->board('2026-06-05', 'month'));
    }

    public function test_invalid_or_unsupported_date_fails_instead_of_inventing_a_calendar(): void
    {
        $this->expectException(\RuntimeException::class);
        app(KigakuCalendar::class)->board('2100-01-01', 'day');
    }
}
